
using ResourceManager.TranslationApi.Models;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Xml.Linq;

namespace ResourceManager.TranslationApi.Services;

public class TranslationService
{
    private readonly HttpClient _httpClient;
    private readonly IConfiguration _configuration;

    public TranslationService(
        HttpClient httpClient,
        IConfiguration configuration)
    {
        _httpClient = httpClient;
        _configuration = configuration;
    }


    public async Task<TranslationResponse> TranslateAsync(
        TranslationRequest request)
    {
        // Gemini API key from the configuration 
        string? apiKey = _configuration["Gemini:ApiKey"];

        if (string.IsNullOrWhiteSpace(apiKey))
            throw new InvalidOperationException(
                "Gemini API key is missing");

        if (request.Items.Count == 0)
            throw new ArgumentException(
                "The translation list is empty");


        string inputJson = JsonSerializer.Serialize(request.Items);

        Console.WriteLine("DANE WYSYŁANE DO GEMINI:");
        Console.WriteLine(inputJson);
        // Prompt AI
        string prompt = $$"""
        You are a professional software localization translator.

        Translate all provided Polish resource texts into {{request.TargetLanguage}}.

        Rules:
        - Preserve every resource key exactly.
        - Translate every item.
        - Preserve placeholders such as {0}, {name} and format strings.
        - Preserve technical identifiers and markup.
        - Use natural language suitable for a software application.
        - Use comments as translation context.
        - Return only valid JSON.
        - Do not omit any resource.

        Expected JSON format:
        {
         "translations": [
          {
            "key": "ResourceKey",
            "translatedText": "translation"
          }]
        }

        Resources:
        {{inputJson}}
        """;

        //  Gemini request content
        var body = new
        {
            contents = new[]
            {
            new
            {
                parts = new[]
                {
                    new { text = prompt }
                }
            }
        },
            generationConfig = new
            {
                responseMimeType = "application/json",
                temperature = 0.2
            }
        };

        string jsonBody = JsonSerializer.Serialize(body);

        using var content = new StringContent(
            jsonBody,
            Encoding.UTF8,
            "application/json");

        // Send request to Gemini
        string url =
            "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent";

        using var httpRequest = new HttpRequestMessage(HttpMethod.Post, url);

        httpRequest.Headers.Add("x-goog-api-key", apiKey);
        httpRequest.Content = content;

        var stopwatch = System.Diagnostics.Stopwatch.StartNew();

        Console.WriteLine("Wysyłam żądanie do Gemini...");

        using var response = await _httpClient.SendAsync(httpRequest);

        Console.WriteLine("Otrzymałem odpowiedź od Gemini!");

        stopwatch.Stop();

        Console.WriteLine($"Gemini response time: {stopwatch.ElapsedMilliseconds} ms");
        Console.WriteLine($"Gemini status: {(int)response.StatusCode}");

        string responseJson = await response.Content.ReadAsStringAsync();

        Console.WriteLine($"Gemini response: {responseJson}");

        response.EnsureSuccessStatusCode();

        using var document = JsonDocument.Parse(responseJson);

        string generatedText = document.RootElement
            .GetProperty("candidates")[0]
            .GetProperty("content")
            .GetProperty("parts")[0]
            .GetProperty("text")
            .GetString()!;

        // Reading the JSON generated by AI
        var result = JsonSerializer.Deserialize<TranslationResponse>(
            generatedText,
            new JsonSerializerOptions
            {
                PropertyNameCaseInsensitive = true
            });

        return result ?? throw new InvalidOperationException(
            "Failed to read translations from the Gemini response");
    }

}
